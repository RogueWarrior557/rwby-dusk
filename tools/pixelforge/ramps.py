#!/usr/bin/env python3
"""ramps — build hue-shifted colour ramps in OKLCH and emit a .pal palette.

Hue shifting: in a ramp, darker steps rotate toward a cool "shadow hue"
(blue-violet) and lighter steps toward a warm "light hue" (yellow), and
chroma peaks in the mid-tones and falls off at both ends. This mimics how
coloured light and ambient sky light behave and is the standard practice in
professional pixel-art palettes. Working in OKLCH keeps lightness steps
perceptually even, so every ramp reads with the same value contrast.

Input is a small JSON spec:

    {"ramps": [
       {"name": "steel", "keys": "1234", "hue": 250, "l": [0.28, 0.86],
        "c": [0.03, 0.06, 0.03], "shift": 18},
       ...],
     "singles": [{"key": "o", "hex": "#140f1e", "name": "outline"}]}

  keys  : one palette key per step, dark -> light
  l     : [darkest, lightest] OKLab lightness
  c     : chroma at [dark end, middle, light end] (piecewise linear)
  shift : max degrees of hue rotation applied at each end
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from PIL import Image, ImageDraw

SHADOW_HUE = 285.0  # blue-violet
LIGHT_HUE = 95.0    # warm yellow


def oklch_to_srgb(l: float, c: float, h_deg: float) -> tuple[int, int, int]:
    h = math.radians(h_deg)
    a, b = c * math.cos(h), c * math.sin(h)
    l_ = l + 0.3963377774 * a + 0.2158037573 * b
    m_ = l - 0.1055613458 * a - 0.0638541728 * b
    s_ = l - 0.0894841775 * a - 1.2914855480 * b
    lc, mc, sc = l_ ** 3, m_ ** 3, s_ ** 3
    r = 4.0767416621 * lc - 3.3077115913 * mc + 0.2309699292 * sc
    g = -1.2684380046 * lc + 2.6097574011 * mc - 0.3413193965 * sc
    bl = -0.0041960863 * lc - 0.7034186147 * mc + 1.7076147010 * sc

    def enc(x: float) -> int:
        x = min(max(x, 0.0), 1.0)
        x = 12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055
        return round(x * 255)

    return enc(r), enc(g), enc(bl)


def rotate_toward(h: float, target: float, amount: float) -> float:
    """Rotate hue h toward target by at most `amount` degrees (shortest way)."""
    diff = (target - h + 540) % 360 - 180
    step = max(-amount, min(amount, diff))
    return (h + step) % 360


def build_ramp(spec: dict) -> list[tuple[str, str, str]]:
    keys: str = spec["keys"]
    n = len(keys)
    l0, l1 = spec["l"]
    c0, cm, c1 = spec["c"]
    shift = spec.get("shift", 15)
    out = []
    for i, key in enumerate(keys):
        t = i / (n - 1) if n > 1 else 0.5
        l = l0 + (l1 - l0) * t
        c = c0 + (cm - c0) * (t / 0.5) if t <= 0.5 else cm + (c1 - cm) * ((t - 0.5) / 0.5)
        # distance from the mid-tone decides how far the hue rotates
        if t < 0.5:
            h = rotate_toward(spec["hue"], SHADOW_HUE, shift * (0.5 - t) / 0.5)
        else:
            h = rotate_toward(spec["hue"], LIGHT_HUE, shift * (t - 0.5) / 0.5)
        r, g, b = oklch_to_srgb(l, c, h)
        out.append((key, f"#{r:02x}{g:02x}{b:02x}", f"{spec['name']}{i}"))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("spec", type=Path)
    ap.add_argument("-o", "--out", type=Path, required=True, help="output .pal path")
    ap.add_argument("--swatch", type=Path, help="optional swatch PNG")
    args = ap.parse_args()
    spec = json.loads(args.spec.read_text())
    rows: list[list[tuple[str, str, str]]] = []
    for single in spec.get("singles", []):
        rows.append([(single["key"], single["hex"], single["name"])])
    for ramp in spec["ramps"]:
        rows.append(build_ramp(ramp))
    seen: set[str] = set()
    lines = [f"// generated by ramps.py from {args.spec.name}; edit the spec, not this file"]
    for row in rows:
        for key, hexcol, name in row:
            if key in seen:
                raise SystemExit(f"duplicate key {key!r}")
            seen.add(key)
            lines.append(f"{key} {hexcol} {name}")
    args.out.write_text("\n".join(lines) + "\n")
    if args.swatch:
        cell = 24
        w = max(len(r) for r in rows) * cell
        img = Image.new("RGB", (w, len(rows) * cell), (20, 18, 26))
        d = ImageDraw.Draw(img)
        for y, row in enumerate(rows):
            for x, (_, hexcol, _) in enumerate(row):
                d.rectangle([x * cell, y * cell, x * cell + cell - 1, y * cell + cell - 1], fill=hexcol)
        img.save(args.swatch)
    print(f"wrote {args.out} ({len(seen)} colours)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
