NAMES = ["bram","sefa","tamsin","nox","isolde","pell","nameless","hester"]

def render(name, fill=(14,10,24,255)):
    img = Image.new("RGBA",(32,32),(0,0,0,0)); px = img.load()
    for y,x0,x1 in HEROES[name]:
        for x in range(x0,x1+1): px[x,y] = fill
    return img

def sheet(scale, bg=(214,200,170,255), gap=4):
    n=len(NAMES); w=(32+gap)*n+gap; h=32+2*gap
    out=Image.new("RGBA",(w,h),bg)
    for i,nm in enumerate(NAMES):
        out.alpha_composite(render(nm),(gap+i*(32+gap),gap))
    return out.resize((w*scale,h*scale),Image.NEAREST)

